function cleanMeaning(meaning: string) {
  return meaning.replace(/^(adj|adv|n|v)\.\s*/i, "").replace(/；(adj|adv|n|v)\.\s*/gi, "；");
}

function affixCue(word: string, meaning: string) {
  const lower = word.toLocaleLowerCase();
  const cues: string[] = [];
  if (lower.startsWith("counter")) cues.push("counter- = against / opposite");
  else if (lower.startsWith("pseudo")) cues.push("pseudo- = false");
  else if (lower.startsWith("pre") && /预|之前|先/.test(meaning)) cues.push("pre- = before");
  else if (lower.startsWith("sub") && /次|下|附属|低/.test(meaning)) cues.push("sub- = under");
  else if (/^(un|in|im|ir|il)/.test(lower) && /不|无|未|非|难以|无法|不能/.test(meaning)) cues.push(`${lower.match(/^(un|in|im|ir|il)/)?.[0]}- = not`);
  if (lower.endsWith("ize")) cues.push("-ize = make / become");
  else if (lower.endsWith("less")) cues.push("-less = without");
  else if (lower.endsWith("ful")) cues.push("-ful = full of");
  else if (lower.endsWith("ist")) cues.push("-ist = person");
  else if (lower.endsWith("tion") || lower.endsWith("sion")) cues.push("-tion / -sion = 名词后缀");
  return cues.join("；");
}

function trustedSynonyms(word: string, plan: GroupPlan) {
  const candidates = new Set<string>();
  if (plan.relation === "synonym") for (const peer of plan.words) if (peer !== word) candidates.add(peer);
  for (const synonym of commonSynonyms[word] ?? []) candidates.add(synonym);
  return [...candidates]
    .filter((candidate) => candidate.toLocaleLowerCase() !== word.toLocaleLowerCase())
    .slice(0, 3)
    .join("；") || undefined;
}

function relationLabel(relation: GroupPlan["relation"]): MindMapLogicLink["label"] {
  if (relation === "synonym") return "同义";
  if (relation === "contrast") return "反义";
  if (relation === "form") return "形近不同义";
  if (relation === "root") return "词根联结";
  return "场景联结";
}

function branchKind(relation: GroupPlan["relation"]): MindMapBranchKind {
  if (relation === "contrast") return "contrast";
  if (relation === "form") return "form";
  if (relation === "root") return "root";
  return "meaning";
}

function wordNote(list: number, plan: GroupPlan, word: string): MindMapWord {
  const entry = entries.get(`${list}:${word.toLocaleLowerCase()}`);
  if (!entry) throw new Error(`List ${list} is missing ${word}`);
  const meaning = cleanMeaning(entry.meaning);
  const peers = plan.words.filter((candidate) => candidate !== word);
  const peerNotes = peers.map((candidate) => {
    const peer = entries.get(`${list}:${candidate.toLocaleLowerCase()}`);
    return peer ? `${candidate}（${cleanMeaning(peer.meaning)}）` : candidate;
  });
  const synonyms = trustedSynonyms(word, plan);
  const formCue = exactMemory[word] ?? affixCue(word, meaning);
  const hasExplicitRelation = plan.relation && plan.relation !== "scene";
  const rootCue = plan.rootExamples ? `常用词辅助：${plan.rootExamples}。` : "";
  const exampleLead = entry.meaning.match(/^([a-z]+)\./i)?.[1]?.toLocaleLowerCase();
  const example = exampleLead === "adj"
    ? `The passage describes it as ${word}. 文中用 ${word} 表示“${meaning}”。`
    : exampleLead === "n"
      ? `The passage calls this ${word}. 文中用 ${word} 指“${meaning}”。`
      : `The passage uses ${word} for the action “${meaning}”.`;
  return {
    word,
    memory: [formCue, rootCue].filter(Boolean).join(" "),
    synonyms,
    relatedWords: hasExplicitRelation && peerNotes.length ? peerNotes.join("；") : undefined,
    example,
  };
}

function buildMap(list: number, part: 1 | 2, groupPlans: GroupPlan[]): GleeMindMap {
  return {
    id: `${list}-${part}`,
    list,
    part,
    branches: groupPlans.map((plan) => {
      const words = plan.words.map((word) => wordNote(list, plan, word));
      const logicLinks = plan.relation && plan.relation !== "scene" ? plan.words.slice(1).map((word, index): MindMapLogicLink => ({
        from: plan.words[index],
        to: word,
        label: relationLabel(plan.relation),
        detail: `${plan.words[index]} 与 ${word} 放在「${plan.title}」中联动核对`,
      })) : [];
      return {
        title: plan.title,
        count: String(words.length),
        kind: branchKind(plan.relation),
        words,
        note: `仿 Glee 讲解：${words.map((item) => `${item.word}＝${cleanMeaning(entries.get(`${list}:${item.word.toLocaleLowerCase()}`)!.meaning)}`).join("；")}。${plan.rootExamples ? ` 常用词辅助：${plan.rootExamples}。` : ""}`,
        logicLinks,
      };
    }),
  };
}

