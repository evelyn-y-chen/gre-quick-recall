function lessonLabel(note: CourseWord) {
  if (note.list === 1) return note.number <= 22 ? "形容词熟词僻义" : "动词熟词僻义";
  if (note.list === 2) return note.number <= 23 ? "动词熟词僻义" : "名词熟词僻义";
  if (note.list === 3) return note.number <= 20 ? "易望文生义词" : "固定短语";
  if (note.list === 4) return "GRE 概念与辨析";
  if (note.list === 5) return "高频构词与词义辨析";
  return "高频词义与搭配";
}

